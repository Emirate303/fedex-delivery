
import nodemailer from "nodemailer";

const TRACKING_PAGE_URL = "https://fedextracking.site.je/";

function getTransporter() {
  const user = process.env.GMAIL_USER;
  const password = process.env.GMAIL_APP_PASSWORD?.replace(/\s/g, "");

  if (!user || !password) {
    throw new Error("Gmail SMTP environment variables are missing.");
  }

  return nodemailer.createTransport({
    host: "smtp.gmail.com",
    port: 465,
    secure: true,
    auth: {
      user,
      pass: password,
    },
  });
}

function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/g, (character) => {
    const entities: Record<string, string> = {
      "&": "&amp;",
      "<": "&lt;",
      ">": "&gt;",
      '"': "&quot;",
      "'": "&#39;",
    };

    return entities[character];
  });
}

function formatDate(date: Date): string {
  return date.toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });
}

async function sendEmail({
  to,
  subject,
  html,
  text,
}: {
  to: string;
  subject: string;
  html: string;
  text: string;
}) {
  const user = process.env.GMAIL_USER;

  if (!user) {
    throw new Error("GMAIL_USER environment variable is missing.");
  }

  const transporter = getTransporter();

  const result = await transporter.sendMail({
    from: {
      name: "FedEx Delivery Notifications",
      address: user,
    },
    to,
    subject,
    text,
    html,
  });

  return {
    data: result,
    error: null,
  };
}

